import { defineConfig, type Plugin } from 'vite';

/**
 * Emits sw.js: a cache-first service worker precaching the built app shell
 * (everything in the bundle; not public/, so the 12 MB demo clip stays out).
 */
function serviceWorker(): Plugin {
  return {
    name: 'tslink-sw',
    enforce: 'post', // after Vite emits index.html, so its content is versioned too
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map')).sort();
      // Version from contents, not names: index.html has no hash in its name.
      const body = (f: string) => {
        const c = bundle[f] as { type: string; code?: string; source?: string | Uint8Array };
        if (c.type === 'chunk') return c.code ?? '';
        if (typeof c.source === 'string') return c.source;
        return c.source ? new TextDecoder().decode(c.source) : '';
      };
      const version = fnv1a(files.map((f) => `${f}\n${body(f)}`).join('\n'));
      const shell = [...new Set(['./', './index.html', ...files.map((f) => `./${f}`)])];
      const src = `// Generated by vite.config.ts. Cache-first app shell.
const CACHE = 'tslink-${version}';
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', (e) => {
  // cache: 'reload' skips the HTTP cache: a stale index.html there would point
  // at assets the new deploy no longer has (blank page).
  e.waitUntil(caches.open(CACHE)
    .then((c) => c.addAll(SHELL.map((u) => new Request(u, { cache: 'reload' })))));
});
// No skipWaiting on install: taking over at once would delete the old cache
// under a page still loading old assets. The page asks for it at startup.
self.addEventListener('message', (e) => { if (e.data === 'activate') self.skipWaiting(); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tslink-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  const scope = self.registration.scope;
  // Navigations (any query string: ?demo=1, ?code=...) get the cached index.html.
  const key = req.mode === 'navigate' ? scope : req;
  // ignoreVary: servers send Vary: Origin, and module/stylesheet requests
  // (crossorigin) carry an Origin header the precache requests didn't, so
  // they'd miss the cache and go to the network, where a newer deploy no
  // longer has these assets.
  e.respondWith(caches.open(CACHE).then((c) => c.match(key, { ignoreSearch: req.mode === 'navigate', ignoreVary: true })
    .then((hit) => hit || fetch(req))));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: src });
    },
  };
}

/**
 * Build id for the debug overlay: `__BUILD__` is defined as a placeholder,
 * which the built chunks then get replaced with "YYMMDD-HHMM-<hash>" (UTC
 * build time + FNV-1a of the chunks' code; no git needed). Same length as the
 * placeholder, so source maps stay right. Dev and tests see the placeholder
 * (main.ts shows "dev").
 */
const BUILD_PLACEHOLDER = '__TSLINK_BUILD_ID__';

function buildId(): Plugin {
  return {
    name: 'tslink-build-id',
    enforce: 'post',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const chunks = Object.keys(bundle).sort().map((f) => bundle[f]).filter((c) => c.type === 'chunk');
      const d = new Date().toISOString(); // 2026-11-15T13:42:...
      const id = `${d.slice(2, 4)}${d.slice(5, 7)}${d.slice(8, 10)}-${d.slice(11, 13)}${d.slice(14, 16)}-`
        + fnv1a(chunks.map((c) => c.code).join('\n'));
      if (id.length !== BUILD_PLACEHOLDER.length) throw new Error(`build id ${id}: wrong length`);
      for (const c of chunks) c.code = c.code.replaceAll(BUILD_PLACEHOLDER, id);
    },
  };
}

/** 32-bit FNV-1a as 8 hex digits. */
function fnv1a(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193) >>> 0;
  return h.toString(16).padStart(8, '0');
}

/**
 * Content-Security-Policy for the built page. Build-only because the Vite dev
 * server injects CSS as inline <style> elements. WebTransport uses https: URLs,
 * hence connect-src https:. No inline styles/scripts are needed: element.style
 * set from script (ripple position) is CSSOM and not governed by style-src.
 */
const CSP = [
  "default-src 'self'",
  "img-src 'self' data:",
  "style-src 'self'",
  "script-src 'self'",
  "connect-src 'self' https:",
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join('; ');

function csp(): Plugin {
  return {
    name: 'tslink-csp',
    apply: 'build',
    transformIndexHtml: () => [{ tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP }, injectTo: 'head-prepend' }],
  };
}

export default defineConfig({
  base: './',
  // Build-id plugin first: the service worker's version then covers the final chunk contents.
  plugins: [csp(), buildId(), serviceWorker()],
  define: { __BUILD__: JSON.stringify(BUILD_PLACEHOLDER) },
  worker: { format: 'es' },
  build: { target: 'es2022', sourcemap: true },
});
